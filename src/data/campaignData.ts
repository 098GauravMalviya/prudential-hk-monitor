// Helper calculations for Theme Distribution across brands
export function getThemeDistribution() {
  const distribution: Record<ContentTheme, Record<string, number>> = {} as any;
  CONTENT_THEMES.forEach((t) => {
    distribution[t] = { prudential: 0, aia: 0, manulife: 0, axa: 0, total: 0 };
  });

  CAMPAIGN_RECORDS.forEach((c) => {
    if (distribution[c.theme]) {
      distribution[c.theme][c.brand] = (distribution[c.theme][c.brand] || 0) + 1;
      distribution[c.theme].total += 1;
    }
  });

  return Object.entries(distribution).map(([theme, counts]) => ({
    theme: theme as ContentTheme,
    ...counts,
  }));
}
